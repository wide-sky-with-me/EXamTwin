"""Render repository documentation for GitHub Wiki without network or Git writes.

Decision: .agents/notes/implemented/process/2026-10-14-single-source-wiki.md
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit, urlunsplit

PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "https://github.com/wide-sky-with-me/EXamTwin"
GENERATED_MARKER = "<!-- Generated by scripts/build_wiki.py; edit the source document. -->"
GROUPS = (
    ("", "总览", ""),
    ("cookbook", "操作指南", "Guide-"),
    ("subsystems", "子系统参考", "Reference-"),
    ("postmortem", "事故复盘", "Postmortem-"),
)
LINK = re.compile(
    r"(?P<start>!?\[[^\]\n]*\]\()(?P<target><[^>\n]+>|[^\s)]+)"
    r"(?P<end>(?:[ \t]+[\"'][^\n]*?[\"'])?\))"
)
REFERENCE = re.compile(r"^(?P<start>\s*\[[^\]\n]+\]:\s*)(?P<target><[^>\n]+>|[^\s]+)")
INLINE_CODE = re.compile(r"(`+)(.*?)\1")
FENCE = re.compile(r"^\s*(`{3,}|~{3,})")


@dataclass(frozen=True)
class WikiPage:
    source: Path
    slug: str
    title: str
    group: str


def discover_pages(root: Path) -> list[WikiPage]:
    root = root.resolve()
    pages: list[WikiPage] = []
    slugs: set[str] = {"_sidebar", "_footer"}
    for directory, group, prefix in GROUPS:
        for source in sorted((root / "docs" / directory).glob("*.md")):
            if source.name == "AGENTS.md":
                continue
            if not source.resolve().is_relative_to(root):
                raise ValueError(f"Documentation escapes the repository: {source}")
            text = source.read_text(encoding="utf-8")
            title = re.search(r"^# (.+)$", text, re.MULTILINE)
            if title is None:
                raise ValueError(f"Missing document title: {source.relative_to(root)}")
            slug = "Home" if source == root / "docs" / "README.md" else prefix + source.stem
            if slug.casefold() in slugs:
                raise ValueError(f"Duplicate wiki page: {slug}")
            slugs.add(slug.casefold())
            pages.append(WikiPage(source.resolve(), slug, title[1], group))
    if "home" not in slugs:
        raise ValueError("docs/README.md is required for the wiki home page")
    return pages


def rewrite_links(
    text: str,
    source: Path,
    root: Path,
    pages: dict[Path, WikiPage],
    ref: str,
) -> str:
    root = root.resolve()

    def target(raw: str) -> str:
        parsed = urlsplit(raw.removeprefix("<").removesuffix(">"))
        if parsed.scheme or parsed.netloc or not parsed.path:
            return raw
        resolved = (source.parent / unquote(parsed.path)).resolve()
        if not resolved.is_relative_to(root) or not resolved.exists():
            raise ValueError(f"Invalid local link in {source.relative_to(root)}: {raw}")
        if resolved in pages:
            path = quote(pages[resolved].slug, safe="-")
        else:
            kind = "tree" if resolved.is_dir() else "blob"
            relative = quote(resolved.relative_to(root).as_posix(), safe="/")
            path = f"{REPOSITORY}/{kind}/{quote(ref, safe='')}/{relative}"
        return urlunsplit(("", "", path, parsed.query, parsed.fragment))

    def prose(part: str) -> str:
        part = LINK.sub(lambda match: match["start"] + target(match["target"]) + match["end"], part)
        return REFERENCE.sub(lambda match: match["start"] + target(match["target"]), part)

    rendered: list[str] = []
    fence: str | None = None
    for line in text.splitlines(keepends=True):
        delimiter = FENCE.match(line)
        if delimiter:
            run = delimiter[1]
            if fence is None:
                fence = run
            elif run[0] == fence[0] and len(run) >= len(fence) and not line.strip().strip(run[0]):
                fence = None
            rendered.append(line)
            continue
        if fence is not None:
            rendered.append(line)
            continue
        cursor = 0
        parts: list[str] = []
        for code in INLINE_CODE.finditer(line):
            parts.extend((prose(line[cursor : code.start()]), code[0]))
            cursor = code.end()
        parts.append(prose(line[cursor:]))
        rendered.append("".join(parts))
    return "".join(rendered)


def render_pages(root: Path | None = None, ref: str = "main") -> dict[str, str]:
    root = (root or PROJECT_ROOT).resolve()
    if not ref or any(char.isspace() for char in ref):
        raise ValueError("A non-empty source ref without whitespace is required")
    pages = discover_pages(root)
    by_source = {page.source: page for page in pages}
    output: dict[str, str] = {}
    for page in pages:
        relative = quote(page.source.relative_to(root).as_posix(), safe="/")
        source_url = f"{REPOSITORY}/blob/{quote(ref, safe='')}/{relative}"
        body = rewrite_links(
            page.source.read_text(encoding="utf-8"), page.source, root, by_source, ref
        )
        output[f"{page.slug}.md"] = (
            f"{GENERATED_MARKER}\n\n{body.rstrip()}\n\n---\n\n[源文档]({source_url})\n"
        )
    sidebar = [GENERATED_MARKER, "", "[ExamTwin](Home)", ""]
    for _, group, _ in GROUPS:
        sidebar.extend((f"### {group}", ""))
        sidebar.extend(
            f"- [{page.title}]({quote(page.slug, safe='-')})"
            for page in pages
            if page.group == group and page.slug != "Home"
        )
        sidebar.append("")
    output["_Sidebar.md"] = "\n".join(sidebar)
    output["_Footer.md"] = (
        f"{GENERATED_MARKER}\n\n[项目仓库]({REPOSITORY}) | "
        f"[文档来源]({REPOSITORY}/tree/{quote(ref, safe='')}/docs)\n"
    )
    return output


def check_output(output: Path, pages: dict[str, str]) -> list[str]:
    errors = []
    for name, text in pages.items():
        path = output / name
        if path.is_symlink() or not path.is_file():
            errors.append(f"Missing or unsafe page: {name}")
        elif path.read_text(encoding="utf-8") != text:
            errors.append(f"Outdated page: {name}")
    for path in sorted(output.glob("*.md")):
        if path.name not in pages and not path.is_symlink() and path.is_file():
            if path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
                errors.append(f"Stale generated page: {path.name}; review its removal explicitly")
    return errors


def write_pages(
    output: Path, pages: dict[str, str], root: Path, *, overwrite: bool = False
) -> None:
    root = root.resolve()
    if output.is_symlink():
        raise ValueError("The output directory must not be a symlink")
    destination = output.resolve()
    protected = ("docs", "backend", "frontend", "scripts", "subject-packs", ".agents", ".git")
    if root.is_relative_to(destination) or any(
        destination.is_relative_to(root / name) for name in protected
    ):
        raise ValueError("Output must not overwrite repository source directories")
    # Preflight every collision before writing any page; unrelated wiki pages stay untouched.
    for name in pages:
        path = destination / name
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError(f"Unsafe output page: {name}")
        if path.is_file() and not overwrite:
            if not path.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
                raise ValueError(f"Hand-written page: {name}; use --overwrite after reviewing it")
    stale = [error for error in check_output(destination, pages) if error.startswith("Stale")]
    if stale:
        raise ValueError("; ".join(stale))
    destination.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (destination / name).write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Page directory; defaults to var/wiki")
    parser.add_argument("--ref", default="main", help="Source ref for repository links")
    parser.add_argument("--check", action="store_true", help="Validate without writing pages")
    parser.add_argument(
        "--overwrite", action="store_true", help="Replace reviewed hand-written pages"
    )
    args = parser.parse_args(argv)
    try:
        pages = render_pages(ref=args.ref)
        if args.check:
            errors = check_output(args.output, pages) if args.output is not None else []
            if errors:
                raise ValueError("\n".join(errors))
        else:
            write_pages(
                args.output or PROJECT_ROOT / "var" / "wiki",
                pages,
                PROJECT_ROOT,
                overwrite=args.overwrite,
            )
    except (OSError, ValueError) as exc:
        print(f"Wiki validation failed: {exc}", file=sys.stderr)
        return 1
    print(f"Wiki {'validated' if args.check else 'generated'}: {len(pages)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
